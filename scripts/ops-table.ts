// Generates the operations table in docs/agent-interface.mdx from the ops registry, so the docs
// cannot drift from the code. CI runs `--check`; a developer runs `--write`.
//
//   bun run scripts/ops-table.ts [--write | --check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Op, registry } from "../packages/core/src/ops";

export const BEGIN = "{/* ops:begin (generated by scripts/ops-table.ts, do not edit) */}";
export const END = "{/* ops:end */}";

/**
 * The CLI command that does the same thing as an operation, where one exists. Written by hand
 * because the CLI is not generated from the registry; `scripts/ops-table.test.ts` checks every
 * key is a real operation and every command is in `longshore`'s usage text.
 */
export const CLI_COMMANDS: Readonly<Record<string, string>> = {
  set_secret: "secret set",
  rotate_secret: "secret rotate",
  delete_secret: "secret delete",
  list_secrets: "secret list",
  create_api_token: "token create",
  incident_freeze: "incident freeze",
  incident_unfreeze: "incident unfreeze",
  incident_status: "incident status",
};

const cell = (s: string): string => s.replaceAll("|", "\\|").replaceAll("\n", " ");

/** Where an operation can be reached. MCP is what the server lists, not what the flag says. */
export function surfaces(op: Op): { rest: string; mcp: boolean; cli: string } {
  const routed = op.auth.type === "token" || registry.signatureOps().includes(op);
  return {
    rest: routed ? `${op.http.method} /api/v1${op.http.path}` : "",
    mcp: registry.mcpOps().includes(op),
    cli: CLI_COMMANDS[op.name] ? `longshore ${CLI_COMMANDS[op.name]}` : "",
  };
}

export function renderTable(): string {
  const out = [
    "| Operation | REST | MCP | CLI | Effect | Role | Auth | Purpose |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const op of registry.ops) {
    const s = surfaces(op);
    out.push(
      `| \`${op.name}\` | ${s.rest ? `\`${s.rest}\`` : "none"} | ${s.mcp ? "yes" : "no"} | ${
        s.cli ? `\`${s.cli}\`` : ""
      } | ${op.effect} | ${op.auth.minRole}${op.roleNote ? " (per org policy)" : ""} | ${
        op.auth.type
      } | ${cell(op.summary)} |`,
    );
  }
  return `${out.join("\n")}\n`;
}

export function applyTable(doc: string): string {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < 0 || b < a)
    throw new Error(`docs/agent-interface.mdx needs ${BEGIN} ... ${END}`);
  return `${doc.slice(0, a + BEGIN.length)}\n\n${renderTable()}\n${doc.slice(b)}`;
}

if (import.meta.main) {
  const path = join(import.meta.dir, "../docs/agent-interface.mdx");
  const doc = readFileSync(path, "utf8");
  const next = applyTable(doc);
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error("docs/agent-interface.mdx is stale: run bun run scripts/ops-table.ts --write");
      process.exit(1);
    }
    console.log("docs/agent-interface.mdx operations table is current");
  } else {
    writeFileSync(path, next);
    console.log("wrote the operations table");
  }
}
