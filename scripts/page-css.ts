// Generates packages/core/src/pages/page-tokens.generated.ts from packages/ui/src/styles.css, so the
// server-rendered pages share the web UI's design tokens (colours, radius, font stacks, light and dark)
// and cannot drift. CI runs `--check` (through scripts/page-css.test.ts); a developer runs `--write`.
//
//   bun run scripts/page-css.ts [--write | --check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
export const STYLES = join(root, "packages/ui/src/styles.css");
export const OUT = join(root, "packages/core/src/pages/page-tokens.generated.ts");

/** Page token name -> the UI token it takes its value from, per scheme (the page uses the UI's subtle background). */
export const MAP: { name: string; light: string; dark: string }[] = [
  { name: "--font-sans", light: "--font-sans", dark: "--font-sans" },
  { name: "--font-mono", light: "--font-mono", dark: "--font-mono" },
  { name: "--bg", light: "--bg-subtle", dark: "--bg" },
  { name: "--bg-muted", light: "--bg-muted", dark: "--bg-muted" },
  { name: "--surface", light: "--surface", dark: "--surface" },
  { name: "--border", light: "--border", dark: "--border" },
  { name: "--border-strong", light: "--border-strong", dark: "--border-strong" },
  { name: "--fg", light: "--fg", dark: "--fg" },
  { name: "--fg-muted", light: "--fg-muted", dark: "--fg-muted" },
  { name: "--accent", light: "--accent", dark: "--accent" },
  { name: "--accent-fg", light: "--accent-fg", dark: "--accent-fg" },
  { name: "--ring", light: "--ring", dark: "--ring" },
  { name: "--danger", light: "--st-failure", dark: "--st-failure" },
  { name: "--danger-bg", light: "--st-failure-bg", dark: "--st-failure-bg" },
  { name: "--radius", light: "--radius", dark: "--radius" },
];

/** The declarations of the block opened by `selector {` (the first match), as name -> value. */
export function block(css: string, selector: string): Map<string, string> {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`styles.css has no "${selector}" block`);
  const open = css.indexOf("{", start);
  const close = css.indexOf("}", open);
  const out = new Map<string, string>();
  for (const m of css.slice(open + 1, close).matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    out.set(m[1] as string, (m[2] as string).trim());
  }
  return out;
}

export function renderTokens(css: string): { light: string; dark: string } {
  const light = block(css, ":root");
  const dark = block(css, ':root:not([data-theme="light"])');
  const get = (m: Map<string, string>, key: string, scheme: string): string => {
    const v = m.get(key);
    if (v === undefined) throw new Error(`styles.css ${scheme} has no ${key}`);
    return v;
  };
  const compact = (v: string): string => v.replace(/\s*,\s*/g, ",");
  const lightDecl = MAP.map((t) => `${t.name}:${compact(get(light, t.light, "light"))}`);
  // The dark block only redeclares what differs; the rest (fonts, radius) inherits the light value.
  const darkDecl = MAP.filter((t) => dark.has(t.dark)).map(
    (t) => `${t.name}:${compact(get(dark, t.dark, "dark"))}`,
  );
  return {
    light: `:root{color-scheme:light dark;${lightDecl.join(";")}}`,
    dark: `@media (prefers-color-scheme:dark){:root{${darkDecl.join(";")}}}`,
  };
}

export function render(css: string = readFileSync(STYLES, "utf8")): string {
  const { light, dark } = renderTokens(css);
  return `// Generated by scripts/page-css.ts from packages/ui/src/styles.css. Do not edit; run
// \`bun run scripts/page-css.ts --write\`. CI fails when it is stale.
export const PAGE_TOKENS_CSS = ${JSON.stringify(`${light}\n${dark}`)};
`;
}

if (import.meta.main) {
  const mode = process.argv[2];
  const next = render();
  if (mode === "--write") writeFileSync(OUT, next);
  else if (mode === "--check") {
    let cur = "";
    try {
      cur = readFileSync(OUT, "utf8");
    } catch {}
    if (cur !== next) {
      console.error("page-tokens.generated.ts is stale: run `bun run scripts/page-css.ts --write`");
      process.exit(1);
    }
  } else {
    console.error("usage: bun run scripts/page-css.ts [--write | --check]");
    process.exit(2);
  }
}
