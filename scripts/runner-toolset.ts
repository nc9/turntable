// Generates the toolset table in docs/compatibility.mdx from a built runner image, so the list
// cannot drift from what the image has. CI builds images/runner and runs `--check`; a developer
// with Docker can run `--write`.
//
//   bun run scripts/runner-toolset.ts --image <ref> [--write | --check]
//
// Each tool is probed inside the image: `command -v` for presence and its own version flag for the
// version (first line). "GitHub" is whether GitHub's ubuntu-latest image has the tool preinstalled
// (see actions/runner-images); it is fixed data in this file.
