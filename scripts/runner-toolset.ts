export const BEGIN = "{/* toolset:begin (generated by scripts/runner-toolset.ts, do not edit) */}";
export const END = "{/* toolset:end */}";

/** The shell that prints `name<TAB>present|absent<TAB>version` for each tool. */
export function probeScript(tools: readonly Tool[] = TOOLS): string {
  const lines = tools.map((t) => {
    const args = t.version.map((a) => `'${a}'`).join(" ");
    return `if command -v ${t.cmd} >/dev/null 2>&1; then v=$(${t.cmd} ${args} 2>&1 | sed -n '${t.line ?? 1}p' | tr '\\t' ' ' | cut -c1-80); printf '%s\\tpresent\\t%s\\n' '${t.cmd}' "$v"; else printf '%s\\tabsent\\t\\n' '${t.cmd}'; fi`;
  });
  return lines.join("\n");
}

export interface Probed {
  cmd: string;
  present: boolean;
  version: string;
}

export function parseProbe(output: string): Probed[] {
  return output
    .split("\n")
    .filter((l) => l.includes("\t"))
    .map((l) => {
      const [cmd = "", state = "", version = ""] = l.split("\t");
      return { cmd, present: state === "present", version: version.trim() };
    });
}

/** The version number in a tool's version line, so a changed build string does not churn the table. */
export function versionOf(line: string): string {
  const m = /(\d+\.\d+(?:\.\d+)?)/.exec(line);
  return m?.[1] ?? line.slice(0, 40);
}

const cell = (s: string): string =>
  s.replaceAll("|", "\\|").replaceAll("{", "&#123;").replaceAll("<", "&lt;");

/** The Markdown table, in the order of TOOLS. */
export function renderTable(probed: readonly Probed[], tools: readonly Tool[] = TOOLS): string {
  const by = new Map(probed.map((p) => [p.cmd, p]));
  const rows = tools.map((t) => {
    const p = by.get(t.cmd);
    const have = p?.present ? `Yes: ${cell(p.version ? versionOf(p.version) : "installed")}` : "No";
    return `| ${t.name} | ${t.github ? "Yes" : "No"} | ${have}${t.note ? `. ${cell(t.note)}` : ""} |`;
  });
  return [
    "| Tool | On GitHub ubuntu-latest | On the Longshore runner image |",
    "| --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/** Replaces the generated block in `doc` (the markers must exist). */
export function replaceBlock(doc: string, table: string): string {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error("docs/compatibility.mdx has no toolset markers");
  return `${doc.slice(0, a + BEGIN.length)}\n\n${table}\n\n${doc.slice(b)}`;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: { image: { type: "string" }, write: { type: "boolean" }, check: { type: "boolean" } },
  });
  if (!values.image || (!values.write && !values.check)) {
    console.error("usage: runner-toolset.ts --image <ref> (--write | --check)");
    process.exit(2);
  }
  const p = Bun.spawn(
    ["docker", "run", "--rm", "--network", "none", "--", values.image, "sh", "-c", probeScript()],
    {
      stdout: "pipe",
      stderr: "inherit",
    },
  );
  const out = await new Response(p.stdout).text();
  if ((await p.exited) !== 0) throw new Error("the probe failed");
  const table = renderTable(parseProbe(out));
  const path = join(import.meta.dir, "../docs/compatibility.mdx");
  const doc = readFileSync(path, "utf8");
  const next = replaceBlock(doc, table);
  if (values.write) {
    writeFileSync(path, next);
    return;
  }
  if (next !== doc) {
    console.error("docs/compatibility.mdx is stale. Generated table:\n");
    console.error(table);
    console.error("\nRun: bun run scripts/runner-toolset.ts --image <ref> --write");
    process.exit(1);
  }
}

if (import.meta.main) await main();
