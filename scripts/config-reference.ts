// Generates the environment reference in docs/configuration.mdx from packages/core/src/config-reference.ts,
// so the docs cannot drift from the code. CI runs `--check`; a developer runs `--write`.
//
//   bun run scripts/config-reference.ts [--write | --check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { AREA_ORDER, CONFIG_VARS } from "../packages/core/src/config-reference";
import { describeType } from "../packages/core/src/settings/define";
import { settingsRegistry } from "../packages/core/src/settings/definitions";

export const BEGIN = "{/* config:begin (generated by scripts/config-reference.ts, do not edit) */}";
export const END = "{/* config:end */}";

const cell = (s: string): string => s.replaceAll("|", "\\|");

export function renderReference(): string {
  const out: string[] = [];
  for (const area of AREA_ORDER) {
    const rows = CONFIG_VARS.filter((v) => v.area === area);
    if (rows.length === 0) continue;
    out.push(
      `### ${area}`,
      "",
      "| Variable | Flag | Default | Description |",
      "| --- | --- | --- | --- |",
    );
    for (const v of rows) {
      out.push(
        `| \`${v.name}\` | ${v.flag ? `\`${v.flag}\`` : ""} | ${v.default ? cell(v.default.startsWith("`") ? v.default : v.default) : ""} | ${cell(v.description)} |`,
      );
    }
    out.push("");
  }
  return out.join("\n");
}

export const SETTINGS_BEGIN =
  "{/* settings:begin (generated by scripts/config-reference.ts, do not edit) */}";
export const SETTINGS_END = "{/* settings:end */}";

const code = (s: string): string => `\`${s.replaceAll("`", "")}\``;

/** Every setting of the registry: scope, type, default, roles, MCP-editability and names. */
export function renderSettings(): string {
  const out = [
    "| Key | Scope | Type | Default | Role | MCP | Environment | TOML | Description |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const d of settingsRegistry.settings) {
    const section =
      d.scope === "instance"
        ? ""
        : d.scope === "org"
          ? "orgs.<slug>."
          : "orgs.<slug>.projects.<slug>.";
    const [head, ...rest] = d.toml.split(".");
    const toml = rest.length > 0 ? `[${section}${head}] ${rest.join(".")}` : `${section}${d.toml}`;
    out.push(
      `| ${code(d.key)} | ${d.scope} | ${cell(describeType(d))} | ${code(JSON.stringify(d.default))} | ${d.operatorOnly ? "instance_admin" : d.role} | ${
        d.mcpEditable ? "yes" : `no: ${cell(d.mcpReason ?? "")}`
      } | ${d.env.length > 0 ? d.env.map(code).join(", ") : "none"} | ${code(toml)} | ${cell(d.description)} |`,
    );
  }
  return `${out.join("\n")}\n`;
}

function between(doc: string, begin: string, end: string, body: string): string {
  const a = doc.indexOf(begin);
  const b = doc.indexOf(end);
  if (a < 0 || b < 0 || b < a) throw new Error(`docs/configuration.mdx needs ${begin} ... ${end}`);
  return `${doc.slice(0, a + begin.length)}\n\n${body}\n${doc.slice(b)}`;
}

export function applyReference(doc: string): string {
  return between(
    between(doc, SETTINGS_BEGIN, SETTINGS_END, renderSettings()),
    BEGIN,
    END,
    renderReference(),
  );
}

if (import.meta.main) {
  const path = join(import.meta.dir, "../docs/configuration.mdx");
  const doc = readFileSync(path, "utf8");
  const next = applyReference(doc);
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error(
        "docs/configuration.mdx is stale: run bun run scripts/config-reference.ts --write",
      );
      process.exit(1);
    }
    console.log("docs/configuration.mdx is current");
  } else {
    writeFileSync(path, next);
    console.log("wrote the environment reference");
  }
}
