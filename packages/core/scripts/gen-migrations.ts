// Inlines the drizzle-kit output (drizzle/*.sql + meta/_journal.json) into a TS module.
//
// Why: `bun build --compile` produces one file with no working directory of assets, so a
// runtime read of ./drizzle would fail in an empty directory. A generated module is plain
// bundled source, needs no loader tricks, and is diffable in review. CI re-runs this and
// fails if the committed module is stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { migrationSha } from "../src/db/migration-sha";

const root = join(import.meta.dir, "..");
const goldenPath = join(root, "src/db/migration-shas.json");

// One record per migration, in tag order: the tag is a VALUE, never a key (a key like
// "0030_instance_tokens" next to a 64-hex value reads as a credential to secret scanners).
type GoldenEntry = { tag: string; sha256: string };
type Golden = { "//": string; sqlite: GoldenEntry[]; pg: GoldenEntry[] };
const GOLDEN_NOTE =
  "Golden sha256 of every shipped migration, per dialect (see migration-sha.ts). Embedded, never read from disk at runtime. " +
  "A new migration appends its entry in its own PR (db:generate does it). An existing entry may change ONLY if its tag " +
  "is also in EDITED_IN_PLACE (migration-sha.ts) with a reason: a changed hash refuses boot on every database that applied it.";
const golden: Golden = existsSync(goldenPath)
  ? (JSON.parse(readFileSync(goldenPath, "utf8")) as Golden)
  : { "//": GOLDEN_NOTE, sqlite: [], pg: [] };
golden["//"] = GOLDEN_NOTE;

/** Inlines one drizzle-kit output directory as a TS module. */
function embed(dir: string, out: string, label: "sqlite" | "pg", unqualify = false): void {
  const journal = JSON.parse(readFileSync(join(root, dir, "meta/_journal.json"), "utf8")) as {
    entries: { idx: number; tag: string; when: number }[];
  };
  const migrations = journal.entries.map((entry) => {
    let sql = readFileSync(join(root, dir, `${entry.tag}.sql`), "utf8");
    // drizzle-kit writes `"public"."table"` in foreign keys. Dropped, a migration follows the
    // connection's search_path, so it works in any schema (the tests give each database its own).
    if (unqualify) sql = sql.replaceAll('"public".', "");
    return {
      tag: entry.tag,
      when: entry.when,
      statements: sql
        .split("--> statement-breakpoint")
        .map((s) => s.trim())
        .filter((s) => s.length > 0),
    };
  });
  // Only appends: an existing record is never rewritten, so an edit to an old migration is caught
  // by the golden test instead of being silently re-pinned.
  for (const m of migrations) {
    if (!golden[label].some((e) => e.tag === m.tag))
      golden[label].push({ tag: m.tag, sha256: migrationSha(m) });
  }
  golden[label].sort((a, b) => (a.tag < b.tag ? -1 : a.tag > b.tag ? 1 : 0));
  const body = `// Generated by scripts/gen-migrations.ts from drizzle-kit output (${label === "pg" ? "postgres" : label}). Do not edit.
import type { Migration } from "./migrate";

export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};
`;
  writeFileSync(join(root, out), body);
  console.log(`embedded ${migrations.length} ${label} migration(s)`);
}

embed("drizzle", "src/db/migrations.generated.ts", "sqlite");
embed("drizzle-pg", "src/db/migrations.pg.generated.ts", "pg", true);
writeFileSync(goldenPath, `${JSON.stringify(golden, null, 2)}\n`);
