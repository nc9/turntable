// Inlines the drizzle-kit output (drizzle/*.sql + meta/_journal.json) into a TS module.
//
// Why: `bun build --compile` produces one file with no working directory of assets, so a
// runtime read of ./drizzle would fail in an empty directory. A generated module is plain
// bundled source, needs no loader tricks, and is diffable in review. CI re-runs this and
// fails if the committed module is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8")) as {
  entries: { idx: number; tag: string; when: number }[];
};

const migrations = journal.entries.map((entry) => {
  const sql = readFileSync(join(root, "drizzle", `${entry.tag}.sql`), "utf8");
  return {
    tag: entry.tag,
    when: entry.when,
    statements: sql
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter((s) => s.length > 0),
  };
});

const out = `// Generated by scripts/gen-migrations.ts from drizzle-kit output. Do not edit.
import type { Migration } from "./migrate";

export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(root, "src/db/migrations.generated.ts"), out);
console.log(`embedded ${migrations.length} migration(s)`);
