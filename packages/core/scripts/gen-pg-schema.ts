// Writes the Postgres mirror of the SQLite schema and the dialect selector.
//
//   src/db/schema.sqlite.ts   the hand-written schema (the source of truth)
//   src/db/schema.pg.ts       GENERATED here: the same tables on drizzle's pg-core
//   src/db/schema.ts          GENERATED here: re-exports schema.sqlite and overrides every table
//                             with the one for the dialect this process runs (see dialect.ts)
//
// The schema uses portable types only (text ids, epoch-ms integers, 0/1 or boolean flags, JSON as
// text), so the mirror is a mechanical rewrite and never hand-edited. CI re-runs this and fails
// if a generated file is stale. `bun run db:pg-schema` regenerates.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const src = readFileSync(join(root, "src/db/schema.sqlite.ts"), "utf8");

/** Integer columns that hold offsets, sequence numbers or ids, which must not stop at 2^31. */
const WIDE = new Set([
  "offset",
  "seq",
  "last_seq",
  "log_offset",
  "at_offset",
  "omitted_bytes",
  "id",
]);

let pg = src;
const must = (cond: boolean, what: string): void => {
  if (!cond)
    throw new Error(
      `gen-pg-schema: ${what}; the SQLite schema uses something the mirror does not handle`,
    );
};

pg = pg.replace(
  /import \{[^}]*\} from "drizzle-orm\/sqlite-core";/,
  `import {
  bigint,
  boolean,
  check,
  customType,
  foreignKey,
  index,
  integer,
  pgTable,
  primaryKey,
  text,
  unique,
} from "drizzle-orm/pg-core";`,
);
must(pg.includes("drizzle-orm/pg-core"), "no sqlite-core import to replace");
pg = pg.replace(/\bsqliteTable\(/g, "pgTable(");
pg = pg.replace(
  /const nowMs = sql`\(unixepoch\(\) \* 1000\)`;/,
  "const nowMs = sql`((extract(epoch from now()) * 1000)::bigint)`;",
);
must(pg.includes("extract(epoch"), "no nowMs default to replace");
pg = pg.replaceAll(
  /integer\("([a-z_]+)", \{ mode: "number" \}\)/g,
  'bigint("$1", { mode: "number" })',
);
pg = pg.replaceAll(/integer\("([a-z_]+)", \{ mode: "timestamp_ms" \}\)/g, 'timestampMs("$1")');
pg = pg.replaceAll(/integer\("([a-z_]+)", \{ mode: "boolean" \}\)/g, 'boolean("$1")');
pg = pg.replaceAll(/blob\("([a-z_]+)", \{ mode: "buffer" \}\)/g, 'bytea("$1")');
pg = pg.replaceAll(
  /integer\("id"\)\.primaryKey\(\{ autoIncrement: true \}\)/g,
  'bigint("id", { mode: "number" }).primaryKey().generatedAlwaysAsIdentity()',
);
pg = pg.replaceAll(/integer\("([a-z_]+)"\)/g, (m, name: string) =>
  WIDE.has(name) ? `bigint("${name}", { mode: "number" })` : m,
);
must(!/integer\("[a-z_]+", \{/.test(pg), "an integer column mode is not mapped");
must(!pg.includes("blob("), "a blob column is not mapped");

// The sqlite table has no CHECK on `format` (the column was added with a plain ALTER); postgres
// keeps it.
const stateCheck =
  '    check("outbound_webhook_endpoints_state_check", inList("state", WEBHOOK_STATES)),\n';
must(pg.includes(stateCheck), "no outbound endpoint state check to add the format check after");
pg = pg.replace(
  stateCheck,
  stateCheck +
    '    check("outbound_webhook_endpoints_format_check", inList("format", WEBHOOK_FORMATS)),\n',
);

// Helpers for the two types pg-core has no equivalent of: a ms timestamp surfaced as a Date, and
// a byte string surfaced as a Buffer (what bun:sqlite returns).
pg = pg.replace(
  "const nowMs =",
  `const timestampMs = customType<{ data: Date; driverData: string | number; notNull: false; default: false }>({
  dataType: () => "bigint",
  fromDriver: (v) => new Date(Number(v)),
  toDriver: (d) => d.getTime(),
});
const bytea = customType<{ data: Buffer; driverData: Buffer | Uint8Array }>({
  dataType: () => "bytea",
  fromDriver: (v) => Buffer.from(v),
  toDriver: (b) => b,
});

const nowMs =`,
);
const banner =
  "// GENERATED by scripts/gen-pg-schema.ts from schema.sqlite.ts. Do not edit; run `bun run db:pg-schema`.\n";
writeFileSync(join(root, "src/db/schema.pg.ts"), banner + pg);

const tables = [...src.matchAll(/^export const (\w+) = sqliteTable\(/gm)].map(
  (m) => m[1] as string,
);
must(tables.length > 20, "found too few tables");
const sel =
  `// GENERATED by scripts/gen-pg-schema.ts. Do not edit; run \`bun run db:pg-schema\`.\n` +
  `// Everything the SQLite schema exports, with each table replaced by the one for this process's\n` +
  `// dialect. The tables are typed as the SQLite ones: repos use only the query surface the two\n` +
  `// dialects share, and the dialect is fixed before any repo module is loaded (see dialect.ts).\n` +
  `import { DIALECT } from "./dialect";\n` +
  `import * as pg from "./schema.pg";\n` +
  `import * as sqlite from "./schema.sqlite";\n\n` +
  `export * from "./schema.sqlite";\n\n` +
  tables
    .map(
      (t) =>
        `export const ${t} = (DIALECT === "pg" ? pg.${t} : sqlite.${t}) as unknown as typeof sqlite.${t};`,
    )
    .join("\n") +
  "\n";
writeFileSync(join(root, "src/db/schema.ts"), sel);
console.log(`wrote schema.pg.ts and schema.ts (${tables.length} tables)`);
