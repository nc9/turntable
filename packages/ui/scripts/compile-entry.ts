// Prepares the compiled binary's entrypoint: builds the UI, then writes a generated entry that
// embeds every UI file (`with { type: "file" }`), registers them with core, and starts core.
//
//   const entry = await prepareCompileEntry();   // then compile `entry` instead of core's main.ts
//
// Nothing is read from disk at runtime; the files live inside the executable.
import { mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { buildUi, uiDist } from "./build-bundle";

const root = join(import.meta.dir, "../../..");

export async function prepareCompileEntry(opts?: {
  version: string;
  sha: string;
}): Promise<string> {
  const files = await buildUi(opts);
  const outDir = join(root, "packages/ui/dist-entry");
  mkdirSync(outDir, { recursive: true });
  const imports: string[] = [];
  const entries: string[] = [];
  files.forEach((file, i) => {
    const urlPath = `/${relative(uiDist, file).split("\\").join("/")}`;
    imports.push(
      `import f${i} from ${JSON.stringify(relative(outDir, file))} with { type: "file" };`,
    );
    entries.push(`  ${JSON.stringify(urlPath)}: f${i},`);
  });
  const coreUi = relative(outDir, join(root, "packages/core/src/ui-assets"));
  const coreMain = relative(outDir, join(root, "packages/core/src/main"));
  const source = [
    "// Generated by packages/ui/scripts/compile-entry.ts. Do not edit or commit.",
    `import { registerUiAssets } from ${JSON.stringify(coreUi)};`,
    ...imports,
    `registerUiAssets({\n${entries.join("\n")}\n});`,
    // Registration is read per request, so core may start before this line runs.
    `import ${JSON.stringify(coreMain)};`,
    "",
  ].join("\n");
  const entry = join(outDir, "entry.ts");
  writeFileSync(entry, source);
  return entry;
}

if (import.meta.main) console.log(await prepareCompileEntry());
